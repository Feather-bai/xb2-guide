def url(title):
    return WIKI + urllib.parse.quote(title.replace(" ", "_"))


def load(name):
    p = os.path.join(W, name)
    if os.path.exists(p):
        with open(p, encoding="utf-8") as f:
            return json.load(f)
    return None


