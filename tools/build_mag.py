def tidy(text):
    out = []
    for ln in text.split("\n"):
        ln = ln.strip()
        if not ln:
            continue
        # 中文之间被 OCR 插入的空格去掉
        ln = re.sub(r"(?<=[\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])", "", ln)
        ln = re.sub(r"(?<=[\u4e00-\u9fff])\s+(?=[，。、！？；：）」』】])", "", ln)
        ln = re.sub(r"(?<=[（「『【])\s+", "", ln)
        ln = re.sub(r"\s{2,}", " ", ln)
        out.append(ln)
    return out


